begin;
-- =====================================================================
-- 0008_israeli_calendar.sql — גרסה 1.9.0
--   1. הערה לאירוע לוח (calendar_events.note) + מקור (source; 'il-calendar' = חג/מועד).
--   2. חגים, מועדים, ערבי חג וימי זיכרון בישראל לשנת הלימודים תשפ"ז (2026–2027) — לכיתה ח1.
--      התאריכים חושבו מלוח השנה העברי (כולל כללי ההקדמה/דחייה של יום השואה, יום הזיכרון,
--      יום העצמאות ויום רבין). 'holiday' = אין לימודים; 'event' = יום לימודים עם הודעה.
--      ⚠️ טווחי החופשה (חנוכה, פסח וכו') משתנים לפי לוח בית הספר — המחנך יכול לערוך כל אירוע.
-- בטוח להרצה חוזרת: אירוע שכבר קיים (לפי שם) לא נוסף שוב — גם אם המחנך הזיז את התאריך שלו.
-- =====================================================================
alter table public.calendar_events add column if not exists note   text;
alter table public.calendar_events add column if not exists source text;

do $$
declare v_class uuid;
begin
  select id into v_class from public.classes where name = 'ח1';
  if v_class is null then raise notice 'כיתה ח1 לא נמצאה — החגים לא נוספו'; return; end if;

  insert into public.calendar_events (class_id, kind, title, start_date, end_date, note, source)
  select v_class, t.kind::public.calendar_kind, t.title, t.s::date, t.e::date, t.note, 'il-calendar'
  from (values
    -- ---------- תשרי ----------
    ('holiday', 'ראש השנה',                 '2026-09-11', '2026-09-13', 'ערב החג ושני ימי ראש השנה'),
    ('event',   'צום גדליה',                '2026-09-14', '2026-09-14', null),
    ('holiday', 'יום כיפור',                '2026-09-20', '2026-09-21', 'ערב יום הכיפורים ויום הכיפורים'),
    ('holiday', 'סוכות ושמחת תורה',          '2026-09-25', '2026-10-03', 'ערב סוכות, סוכות, חול המועד ושמחת תורה — לעדכן לפי לוח בית הספר'),
    -- ---------- חשוון–טבת ----------
    ('event',   'יום הזיכרון ליצחק רבין',    '2026-10-22', '2026-10-22', 'י"ב בחשוון חל ביום שישי — מצוין ביום חמישי'),
    ('event',   'חג הסיגד',                 '2026-11-09', '2026-11-09', null),
    ('event',   'חנוכה',                    '2026-12-05', '2026-12-12', 'חופשת חנוכה — לעדכן לפי לוח בית הספר (אפשר לשנות לסוג "חופשה")'),
    ('event',   'צום עשרה בטבת',             '2026-12-20', '2026-12-20', null),
    -- ---------- שבט–אדר ----------
    ('event',   'ט"ו בשבט',                 '2027-01-23', '2027-01-23', null),
    ('event',   'תענית אסתר',               '2027-03-22', '2027-03-22', null),
    ('holiday', 'פורים',                    '2027-03-23', '2027-03-23', null),
    ('event',   'שושן פורים',               '2027-03-24', '2027-03-24', 'חופשה בירושלים'),
    -- ---------- ניסן–סיוון ----------
    ('holiday', 'פסח',                      '2027-04-21', '2027-04-28', 'ערב פסח עד שביעי של פסח — חופשת פסח לפי לוח בית הספר'),
    ('event',   'יום השואה והגבורה',         '2027-05-04', '2027-05-04', null),
    ('event',   'יום הזיכרון לחללי מערכות ישראל ולנפגעי פעולות האיבה', '2027-05-11', '2027-05-11', null),
    ('holiday', 'יום העצמאות',              '2027-05-12', '2027-05-12', null),
    ('event',   'ל"ג בעומר',                '2027-05-25', '2027-05-25', 'בחלק מבתי הספר יום חופש'),
    ('event',   'יום ירושלים',              '2027-06-04', '2027-06-04', null),
    ('holiday', 'שבועות',                   '2027-06-10', '2027-06-11', 'ערב שבועות וחג השבועות')
  ) as t(kind, title, s, e, note)
  where not exists (
    select 1 from public.calendar_events c
    where c.class_id = v_class and c.source = 'il-calendar' and c.title = t.title
  );
end $$;
